#!/usr/bin/env python3
"""Render selected shot takes with the H3 + Pika sequence used for Rain Return."""
import argparse
from contextlib import contextmanager
import fcntl
import gc
from pathlib import Path
import sys
import time
from types import SimpleNamespace

from studio import ADAPTER_REVISION, FPS, Project, file_sha, media_info, save_json


@contextmanager
def lock(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a") as stream:
        fcntl.flock(stream, fcntl.LOCK_EX | fcntl.LOCK_NB)
        yield


def render(project, jobs, runtime):
    import numpy as np
    import torch
    from pika_h3.runtime import validate_runtime
    from pika_h3.pipeline import KNOTS, resolve_assets
    from pika_h3.core import geometry as G
    from pika_h3.core.conditioning import (
        H3ConditionEncoder, Reference, Request, normalize_references, resolve_geometry,
    )
    from pika_h3.core.evaluation import sample_evaluation_ladder
    from pika_h3.core.loader import apply_lora, build_transformer, load_lora_weights
    from pika_h3.core.media import preflight_reference_specs
    from pika_h3.core.numerics import configure_numerics_backend, prepare_conditioning
    from pika_h3.core.schedules import H3SigmaSchedule
    from pika_h3.core.vae import H3Decoders, write_mp4
    from pika_h3.core.wrapper import H3DiffusionWrapper

    validate_runtime()
    if not torch.cuda.is_available() or torch.cuda.get_device_properties(0).total_memory < 76 * 2**30:
        raise RuntimeError("The staged Ref2VA profile needs an 80 GB or 96 GB class CUDA GPU.")
    width, height = project.canvas[:2]

    def load(path):
        # These files are generated by this renderer in the private runtime.
        return torch.load(path, map_location="cpu", weights_only=False)

    def store(path, payload):
        temporary = path.with_suffix(".partial")
        torch.save(payload, temporary)
        temporary.replace(path)

    def release():
        gc.collect()
        torch.cuda.empty_cache()

    base, adapter, manifest = resolve_assets(SimpleNamespace(task="ref2va",
        base_path=runtime / "base", adapter_path=runtime / "adapter" / "ref2va",
        revision=ADAPTER_REVISION))
    policy = manifest["numerics_policy"]
    configure_numerics_backend(policy, runtime="inference")
    pending = [job for job in jobs if not (job.folder / "latents.pt").exists()]
    to_encode = [job for job in pending if not (job.folder / "condition.pt").exists()]
    if to_encode:
        encoder = H3ConditionEncoder(str(base), device="cuda", keep_loaded=True)
        normalized = {}
        for job in to_encode:
            specs = [f"{kind}:{path}" for kind, path in job.refs]
            preflight_reference_specs(specs)
            refs = [Reference.from_spec(spec) for spec in specs]
            frames = G.align_num_frames(job.frames)
            request = Request(task="ref2va", prompt=job.prompt, references=refs, height=height, width=width,
                              num_frames=frames, reference_rule="tiered",
                              reference_short_edge=640 if len(job.row["cast"]) > 2 else 768, keyframe_fit="crop")
            geometry = resolve_geometry(request)
            refs, sizes = normalize_references(request, geometry)
            normalized[job.id] = refs, sizes
            path = job.folder / "text.pt"
            if not path.is_file():
                print(f"{job.id} · encoding prompt", flush=True)
                with torch.inference_mode():
                    embeds, tags = encoder.encode_text(request, [], [], references=refs)
                store(path, {"prompt_embeds": embeds.unsqueeze(0), "text_token_tags": tags, "geometry": geometry})
        encoder.free("text")
        cached = {}
        for job in to_encode:
            print(f"{job.id} · encoding references", flush=True)
            refs, sizes = normalized[job.id]
            entries = []
            with torch.inference_mode():
                for spec, ref in zip(job.refs, refs, strict=True):
                    # Image normalization may change with the reference limit of each shot.
                    cache_key = (spec, 640 if len(job.row["cast"]) > 2 else 768)
                    if cache_key not in cached:
                        entry = {"kind": ref.kind}
                        if ref.kind == "image":
                            entry["video_latents"] = encoder.encode_image_latent(ref.image)
                        if ref.has_audio:
                            entry["audio_latents"] = encoder.encode_audio_latent(ref.audio)
                        cached[cache_key] = entry
                    entries.append(cached[cache_key])
            cond = load(job.folder / "text.pt")
            cond.update(keyframes=[], references=entries, reference_images=sizes)
            store(job.folder / "condition.pt", cond)
        encoder.free()
        del encoder, cached, cond, normalized
        release()

    if pending:
        print("Loading the Ref2VA transformer", flush=True)
        model = build_transformer(str(base), dtype=torch.bfloat16, device="cpu", subfolder=manifest["trunk"])
        apply_lora(model, rank=manifest["rank"], alpha=manifest["alpha"],
                   target_modules=manifest.get("target_modules"), master_dtype=torch.bfloat16)
        load_lora_weights(model, str(adapter))
        model.requires_grad_(False).eval()
        wrapper = H3DiffusionWrapper(model).eval().to("cuda")
        dtypes = {p.dtype for p in model.parameters()}
        if torch.bfloat16 not in dtypes or not dtypes <= {torch.bfloat16, torch.float32}:
            raise RuntimeError(f"Unexpected transformer precision: {dtypes}")
        schedule = H3SigmaSchedule({"denoising_step_list": KNOTS, "video_score_sigma_shift": 12,
                                   "audio_score_sigma_shift": 3}, device="cuda")
        for job in pending:
            print(f"{job.id} · sampling six steps", flush=True)
            started = time.monotonic()
            cond = load(job.folder / "condition.pt")
            geom = cond["geometry"]
            torch.cuda.reset_peak_memory_stats()
            with torch.inference_mode():
                video, audio = sample_evaluation_ladder(
                    wrapper, conditional_dict=prepare_conditioning(cond, "cuda", policy=policy),
                    video_shape=[1, geom.num_latent_frames, G.VIDEO_LATENT_CHANNELS, geom.latent_height, geom.latent_width],
                    audio_shape=[1, geom.num_audio_latents, G.AUDIO_EXTERNAL_DIM],
                    sigmas_v=schedule.video_ladder, sigmas_a=schedule.audio_ladder, seed=job.row["seed"], device="cuda")
            video, audio = video[0].cpu(), audio[0].cpu()
            if not torch.isfinite(video).all() or not torch.isfinite(audio).all():
                raise RuntimeError(f"{job.id}: non-finite latents")
            store(job.folder / "latents.pt", {"video": video, "audio": audio, "sampling_seconds": time.monotonic()-started,
                  "peak_allocated_bytes": torch.cuda.max_memory_allocated()})
            del cond, video, audio
            release()
        del wrapper, model, schedule
        release()

    decoders = H3Decoders(str(base), device="cuda")
    for job in jobs:
        print(f"{job.id} · decoding", flush=True)
        started = time.monotonic()
        pack = load(job.folder / "latents.pt")
        with torch.inference_mode():
            pixels = decoders.decode_video(pack["video"])
            wave = decoders.decode_audio(pack["audio"])
        frames = G.align_num_frames(job.frames)
        if pixels.shape != (frames, height, width, 3) or not np.isfinite(wave).all():
            raise RuntimeError(f"{job.id}: invalid decoded video or audio")
        temporary = job.folder / "clip.partial.mp4"
        wave = wave[:, :round(frames / FPS * G.AUDIO_SAMPLE_RATE)]
        write_mp4(str(temporary), pixels, audio=wave)
        temporary.replace(job.media)
        save_json(job.folder / "render.json", {
            "key": job.key, "sha256": file_sha(job.media), "frames": frames, "fps": FPS,
            "sampling_seconds": pack["sampling_seconds"], "decode_seconds": time.monotonic() - started,
            "peak_allocated_bytes": pack["peak_allocated_bytes"], "gpu": torch.cuda.get_device_name(),
            "torch": torch.__version__, "adapter_sha256": manifest["sha256"],
        })
        media_info(job)
        print(f"{job.id} · ready for review", flush=True)
        del pixels, wave, pack
        release()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project", type=Path)
    parser.add_argument("ids", nargs="+")
    parser.add_argument("--runtime", type=Path, required=True)
    args = parser.parse_args()
    try:
        project = Project(args.project)
        selected = project.select(args.ids)
        with lock(args.runtime / "render.lock"):
            jobs = []
            for job in selected:
                if job.source:
                    raise ValueError(f"{job.id}: imported media is already a take.")
                if (job.folder / "render.json").is_file():
                    media_info(job)
                    print(f"{job.id} · existing take verified", flush=True)
                else:
                    job.folder.mkdir(parents=True, exist_ok=True)
                    jobs.append(job)
            if jobs:
                render(project, jobs, args.runtime.resolve())
    except (ValueError, RuntimeError, OSError, KeyError, TypeError) as error:
        print(f"Render failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
